-- ---------------------------------------------------------------------
--  Sincronizacion de las secuencias de identidad
--  Obligatorio: la carga inicial inserto identificadores explicitos,
--  lo que no avanza los generadores IDENTITY. Sin este paso, el
--  primer INSERT desde la aplicacion chocaria con una llave duplicada.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('rol', 'id_rol'),
            ('usuario', 'id_usuario'),
            ('categoria', 'id_categoria'),
            ('producto', 'id_producto'),
            ('proveedor', 'id_proveedor'),
            ('cliente', 'id_cliente'),
            ('compra', 'id_compra'),
            ('detalle_compra', 'id_detalle_compra'),
            ('venta', 'id_venta'),
            ('detalle_venta', 'id_detalle_venta'),
            ('capa_inventario', 'id_capa'),
            ('consumo_capa', 'id_consumo'),
            ('movimiento_inventario', 'id_movimiento'),
            ('bitacora', 'id_bitacora')
        ) AS t(tabla, columna)
    LOOP
        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE((SELECT MAX(%I) FROM %I), 1))',
            r.tabla, r.columna, r.columna, r.tabla);
    END LOOP;
END $$;
