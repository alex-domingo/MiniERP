UPDATE producto p
SET    stock_actual = COALESCE((
           SELECT SUM(CASE WHEN m.tipo_movimiento = 'ENTRADA' THEN  m.cantidad
                           WHEN m.tipo_movimiento = 'SALIDA'  THEN -m.cantidad
                      END)
           FROM   movimiento_inventario m
           WHERE  m.id_producto = p.id_producto
       ), 0);

